def blk(s):
    return s.replace('\n', '\n> ')

def fmt_A_before(q):
    b = q.get('background', '') or ''
    d = q.get('aiDraft', '') or ''
    out = []
    if b.strip():
        out.append(f'> **任务背景**：{b.strip()}')
    if d.strip():
        out.append(f'> **AI 初稿**：{d.strip()}')
    return '\n'.join(out)

def fmt_A_after(q):
    b = q.get('background', '') or ''
    d = q.get('aiDraft', '') or ''
    kf = '、'.join(q.get('keyFacts') or []) or '—'
    mf = '、'.join(q.get('mustFix') or []) or '—'
    ch = '、'.join(q.get('complianceHints') or []) or '—'
    risk = q.get('keyRisks', '') or ''
    out = []
    if b.strip():
        out.append(f'> **任务背景**：{b.strip()}')
    if d.strip():
        out.append(f'> **AI 初稿**：{d.strip()}')
    if risk.strip():
        out.append(f'> **埋设的陷阱**：{risk.strip()}')
    out.append(f'> **评分字段**：keyFacts：{kf}；mustFix：{mf}；complianceHints：{ch}')
    return '\n'.join(out)

def fmt_B_options(q):
    best = good = inv = risk = ''
    for o in q.get('options', []):
        t = o.get('type', '')
        txt = o.get('text', '')
        if t == 'best': best = txt
        elif t == 'good': good = txt
        elif t == 'invalid': inv = txt
        elif t == 'risk': risk = txt
    return best, good, inv, risk

